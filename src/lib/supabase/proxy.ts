import { createServerClient } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";
import type { Database } from "@/lib/database.types";
import { getSupabaseConfig } from "./config";

export async function updateSession(request: NextRequest) {
  let response = NextResponse.next({ request });
  const config = getSupabaseConfig();
  const path = request.nextUrl.pathname;
  const protectedRoute = path === "/dashboard" || path.startsWith("/dashboard/") || path === "/logout";

  function loginRedirect() {
    const url = request.nextUrl.clone();
    url.pathname = "/login";
    url.search = "";
    url.searchParams.set("next", path + request.nextUrl.search);
    const redirect = NextResponse.redirect(url);
    response.cookies.getAll().forEach((cookie) => redirect.cookies.set(cookie));
    redirect.headers.set("Cache-Control", "private, no-store");
    return redirect;
  }

  if (!config) return protectedRoute ? loginRedirect() : response;

  const supabase = createServerClient<Database>(config.url, config.key, {
    cookies: {
      getAll: () => request.cookies.getAll(),
      setAll(cookiesToSet) {
        cookiesToSet.forEach(({ name, value }) => request.cookies.set(name, value));
        response = NextResponse.next({ request });
        cookiesToSet.forEach(({ name, value, options }) => response.cookies.set(name, value, options));
      },
    },
  });

  // Verify the JWT, and refresh cookies if required. Never trust getSession() here.
  const { data, error } = await supabase.auth.getClaims();
  if (protectedRoute && (error || !data?.claims?.sub)) return loginRedirect();
  response.headers.set("Cache-Control", "private, no-store");
  return response;
}
